#!/usr/bin/env python3
"""Periodic advection-diffusion PDE benchmark for Koopman-based DMD/EDMD upsampling.

This script evaluates the periodic advection--diffusion PDE system whose
temporal evolution is generated by a linear spatial differential operator.
DMD-style interpolation is well matched to this equation class, while PDE-FIND
must still recover the active terms u_x and u_xx from sparse noisy observations.
"""
