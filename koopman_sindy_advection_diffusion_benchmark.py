def apply_publication_plot_style() -> None:
    """Apply an optional SciencePlots style with a safe matplotlib fallback."""
    try:
        import scienceplots  # noqa: F401
        plt.style.use(["science", "nature", "no-latex"])
    except Exception:
        plt.rcParams.update({
            "font.family": "serif",
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.grid": True,
            "grid.alpha": 0.25,
        })
    plt.rcParams.update({
        "font.size": 12,
        "axes.labelsize": 12,
        "axes.titlesize": 12,
        "legend.fontsize": 10,
        "xtick.labelsize": 10,
        "ytick.labelsize": 10,
        "lines.linewidth": 1.4,
        "savefig.dpi": 300,
    })

from koopman_sindy_pde_benchmark import (
    EPS,
    PDESystem,
    add_noise,
    coefficient_error,
    fit_pdefind_oracle,
    integrate_pde,
    make_tnew,
    pde_library,
    periodic_wavenumbers,
    pod_edmd_reconstruct,
    pod_optdmd_reconstruct,
    spectral_derivative,
    support_f1,
)


def advection_diffusion_system(n: int = 48, L: float = 2.0 * np.pi, c: float = 1.0, nu: float = 0.02, T: float = 2.0) -> PDESystem:
    x = np.linspace(0.0, L, n, endpoint=False)
    k = periodic_wavenumbers(n, L)
    u0 = np.sin(x) + 0.35 * np.cos(2 * x + 0.4) + 0.20 * np.sin(3 * x - 0.7)

    def rhs(_t: float, u: np.ndarray) -> np.ndarray:
        ux = spectral_derivative(u, k, 1)
        uxx = spectral_derivative(u, k, 2)
        return -c * ux + nu * uxx

    def true_xi(names: List[str]) -> np.ndarray:
        Xi = np.zeros(len(names))
        idx = {name: i for i, name in enumerate(names)}
        Xi[idx["u_x"]] = -c
        Xi[idx["u_xx"]] = nu
        return Xi

    return PDESystem("advection_diffusion", rhs, u0, (0.0, T), x, {"c": c, "nu": nu, "L": L}, true_xi)



def write_dataset_figure(t_true: np.ndarray, U_true: np.ndarray, x: np.ndarray, outpath: str = "figures/advection_diffusion_dataset.png") -> None:
    """Write a manuscript-ready visualization of the advection--diffusion dataset."""
    apply_publication_plot_style()
    os.makedirs(os.path.dirname(outpath), exist_ok=True)
    fig, axes = plt.subplots(1, 2, figsize=(8.6, 3.8), constrained_layout=False)
    im = axes[0].imshow(
        U_true.T,
        origin="lower",
        aspect="auto",
        extent=[float(t_true[0]), float(t_true[-1]), float(x[0]), float(x[-1])],
    )
    for tt in t_true[::16]:
        axes[0].axvline(float(tt), color="white", lw=0.6, alpha=0.65)
    axes[0].set_title("(a) Field evolution")
    axes[0].set_xlabel(r"$t$")
    axes[0].set_ylabel(r"$x$")
    cbar = fig.colorbar(im, ax=axes[0])
    cbar.set_label(r"$u(t,x)$")

    snapshot_times = [0.0, 1.0, 2.0]
    lines = []
    labels = []
    for target in snapshot_times:
        idx = int(np.argmin(np.abs(t_true - target)))
        line, = axes[1].plot(x, U_true[idx], label=rf"$t={t_true[idx]:.1f}$")
        lines.append(line)
        labels.append(rf"$t={t_true[idx]:.1f}$")
    axes[1].set_title("(b) Periodic snapshots")
    axes[1].set_xlabel(r"$x$")
    axes[1].set_ylabel(r"$u$")
    axes[1].legend(
        lines,
        labels,
        frameon=False,
        loc="upper center",
        ncol=3,
        bbox_to_anchor=(0.5, -0.20),
        borderaxespad=0.0,
        handlelength=1.8,
        columnspacing=1.0,
    )
    fig.subplots_adjust(left=0.08, right=0.98, top=0.90, bottom=0.28, wspace=0.28)
    fig.savefig(outpath, dpi=300, bbox_inches="tight")
    plt.close(fig)

def run(outdir: str = "results/advection_diffusion_benchmark") -> None:
    os.makedirs(outdir, exist_ok=True)
    sys = advection_diffusion_system()
    k = periodic_wavenumbers(len(sys.x), sys.params["L"])
    t_true, U_true = integrate_pde(sys, dt=0.01)
    write_dataset_figure(t_true, U_true, sys.x)
    _, names = pde_library(U_true[:2], k)
    xi_true = sys.true_coefficients(names)
    thresholds = np.array([0.0, 1e-5, 3e-5, 1e-4, 3e-4, 1e-3, 3e-3, 1e-2, 3e-2, 1e-1, 3e-1])
    rows = []
    for sparse_factor in [4, 8, 16]:
        ind = np.arange(0, len(t_true), sparse_factor)
        if ind[-1] != len(t_true) - 1:
            ind = np.r_[ind, len(t_true) - 1]
        t_obs = t_true[ind]
        U_clean_obs = U_true[ind]
        for noise in [0.01, 0.03, 0.05, 0.10]:
            for seed in range(5):
                rng = np.random.default_rng(seed + 1000 * sparse_factor + 100000 * int(noise * 1000))
                U_obs = add_noise(U_clean_obs, noise, rng)
                t_new = make_tnew(t_obs, upsample=5)
                methods = ["baseline", "optdmd", "pod_edmd_rbf"]
                for method in methods:
                    try:
                        if method == "baseline":
                            U_use, t_use, rank = U_obs, t_obs, 0
                            label = "Baseline"
                        elif method == "optdmd":
                            rank = 4
                            U_use = pod_optdmd_reconstruct(U_obs, t_obs, t_new, rank, max_nfev=80)
                            t_use = t_new
                            label = "optDMD"
                        else:
                            rank = 4
                            U_use = pod_edmd_reconstruct(U_obs, t_obs, t_new, rank, "rbf", rng, rbf_centers=12)
                            t_use = t_new
                            label = "POD-EDMD-RBF"
                        if not np.all(np.isfinite(U_use)):
                            raise FloatingPointError("non-finite reconstruction")
                        result = fit_pdefind_oracle(U_use, t_use, k, xi_true, thresholds, rng, max_rows=10000)
                        rows.append({
                            "system": sys.name,
                            "method": method,
                            "method_label": label,
                            "sparse_factor": sparse_factor,
                            "noise": noise,
                            "seed": seed,
                            "upsample": 1 if method == "baseline" else 5,
                            "pod_rank": rank,
                            "support_f1": float(result["f1"]),
                            "coef_error": float(result["coef_error"]),
                            "practical_score": float(result["score"]),
                            "threshold": float(result["threshold"]),
                            "status": "ok",
                        })
                    except Exception as exc:
                        rows.append({
                            "system": sys.name,
                            "method": method,
                            "method_label": {"baseline":"Baseline", "optdmd":"optDMD", "pod_edmd_rbf":"POD-EDMD-RBF"}[method],
                            "sparse_factor": sparse_factor,
                            "noise": noise,
                            "seed": seed,
                            "upsample": 1 if method == "baseline" else 5,
                            "pod_rank": 0 if method == "baseline" else 4,
                            "support_f1": np.nan,
                            "coef_error": np.nan,
                            "practical_score": np.nan,
                            "threshold": np.nan,
                            "status": f"fail: {type(exc).__name__}: {exc}",
                        })
    raw = pd.DataFrame(rows)
    raw.to_csv(os.path.join(outdir, "advection_diffusion_raw.csv"), index=False)
    overall = raw.groupby(["method", "method_label"], as_index=False).agg(
        support_f1_mean=("support_f1", "mean"),
        coef_error_median=("coef_error", "median"),
        practical_score_mean=("practical_score", "mean"),
    )
    overall.to_csv(os.path.join(outdir, "advection_diffusion_summary.csv"), index=False)
    noise = raw.groupby(["noise", "method_label"])["coef_error"].median().unstack()
    sparse = raw.groupby(["sparse_factor", "method_label"])["coef_error"].median().unstack()
    noise.to_csv(os.path.join(outdir, "advection_diffusion_coeferr_by_noise.csv"))
    sparse.to_csv(os.path.join(outdir, "advection_diffusion_coeferr_by_sparse_factor.csv"))
    win_rows = []
    base = raw[(raw.method == "baseline") & (raw.get("status", "ok") == "ok")].sort_values(["sparse_factor", "noise", "seed"])
    for method in ["optdmd", "pod_edmd_rbf"]:
        meth = raw[(raw.method == method) & (raw.get("status", "ok") == "ok")].sort_values(["sparse_factor", "noise", "seed"])
        merged = base.merge(meth, on=["sparse_factor", "noise", "seed"], suffixes=("_base", "_method"))
        win_rows.append({
            "method": method,
            "method_label": meth["method_label"].iloc[0] if len(meth) else method,
            "matched_cases": len(merged),
            "coef_error_win_rate": float((merged.coef_error_method < merged.coef_error_base).mean()) if len(merged) else np.nan,
            "practical_score_win_rate": float((merged.practical_score_method > merged.practical_score_base).mean()) if len(merged) else np.nan,
        })
    pd.DataFrame(win_rows).to_csv(os.path.join(outdir, "advection_diffusion_winrate_vs_baseline.csv"), index=False)
    print(overall.to_string(index=False))
    print("Wrote", outdir)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run the periodic advection-diffusion PDE benchmark.")
    parser.add_argument("--outdir", default="results/advection_diffusion_benchmark")
    args = parser.parse_args()
    run(args.outdir)
